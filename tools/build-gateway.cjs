// The published script is generated, never patched by the tunnel publisher.
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const REVISION = 'd5060d3c4868cf6676ac191a1aa7708b78fa6b6d';
const SHA256 = 'ed5176f3301b7412b1627040ef85357684c5525b995672f66389a1787304ef80';

function buildGateway(client, bootstrap) {
  if (crypto.createHash('sha256').update(client).digest('hex') !== SHA256) {
    throw new Error('Unexpected pinned client hash; refusing to generate the script');
  }
  const anchor = 'local FOLDER = "UAI"';
  if (client.split(anchor).length !== 2) throw new Error('Expected one storage isolation anchor');
  const isolated = client.replace(anchor, 'local FOLDER = "UAI-Compat-3.7.1"');
  const license = fs.readFileSync(path.join(__dirname, '../LICENSE'), 'utf8').trimEnd();
  return `-- GENERATED by tools/build-gateway.cjs; edit src/gateway_bootstrap.lua instead.
-- Embedded ProjectUAI revision: ${REVISION}
-- Original SHA-256: ${SHA256}
-- Only upstream modification: compatibility storage folder isolation.
--[[
${license}
]]
local function startClient(...)
${isolated.trimEnd()}
end

local function gatewayBootstrap(...)
${bootstrap.trimEnd()}
end

return gatewayBootstrap(startClient, ...)
`;
}

module.exports = {buildGateway};

if (require.main === module) {
  const checkout = process.argv[2];
  if (!checkout) throw new Error('Usage: node tools/build-gateway.cjs <ProjectUAI checkout> [--check]');
  const root = path.join(__dirname, '..');
  const artifact = buildGateway(fs.readFileSync(path.join(checkout, 'dist/uai.lua'), 'utf8'),
    fs.readFileSync(path.join(root, 'src/gateway_bootstrap.lua'), 'utf8'));
  const output = path.join(root, 'examples/gateway.lua');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8') !== artifact) throw new Error('Generated gateway.lua is out of date');
    console.log('Generated artifact matches verified sources');
  } else {
    fs.writeFileSync(output, artifact);
    console.log(`Generated examples/gateway.lua (${Buffer.byteLength(artifact)} bytes)`);
  }
}
